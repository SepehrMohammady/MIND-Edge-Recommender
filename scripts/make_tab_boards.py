"""Write the table of the 8-bit encoders on our STM32H7B3I-DK (paper/tab_boards.tex) from
paper/results/board/STM32H7B3I-DK_sweep.json (scripts/board_sweep.py), so no number is typed by hand.

    python -m scripts.make_tab_boards
"""
import json
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sweep = json.loads((ROOT / "paper/results/board/STM32H7B3I-DK_sweep.json").read_text(encoding="utf-8"))
rows = {r["model"]: r for r in sweep["rows"]}
# the names of Table 3 (scripts/make_tab_unas.py)
LABELS = [("STM32H7B3I-DK budget", [("unas_h7", r"$\mu$NAS 144, recipe choice"), ("unas_h7_c140", r"$\mu$NAS 140, final choice"),
                                     ("hand_64-2-384", "Hand-designed 64-2-384")]),
          ("NUCLEO-F401RE budget", [("unas_f401", r"$\mu$NAS 134, recipe choice"), ("unas_f401_c142", r"$\mu$NAS 142, final choice"),
                                     ("hand_32-5-384", "Hand-designed 32-5-384")]),
          ("Outside both MAC budgets", [("hand_64-5-384", "Hand-designed 64-5-384")])]


def f1(x):
    return str(Decimal(str(x)).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))


lines = ["% Generated by scripts/make_tab_boards.py from paper/results/board/STM32H7B3I-DK_sweep.json; do not edit.",
         r"\begin{table}[t]",
         r"\caption{Milliseconds per title of the 8-bit files of Table~\ref{tab:unas} on an STM32H7B3I-DK: ST's",
         r"benchmark board (Developer Cloud, ST Edge AI Core 4.0.1) and ours (Core 4.0.0, ST's validation firmware)",
         r"with the code generator's default setting and with time optimisation (\texttt{-O time}). Ten random",
         r"inputs each; on our board the outputs equal those of the ONNX models to within an RMSE of",
         f"{max(max(r['balanced_rmse'], r['time_rmse']) for r in sweep['rows']):.4f}" + ".}",
         r"\label{tab:boards}\centering\scriptsize",
         r"\begin{tabular}{lccc}",
         r"\toprule",
         r"Encoder & ST's board & Ours, default & Ours, \texttt{-O time}\\",
         r"\midrule"]
for i, (group, items) in enumerate(LABELS):
    if i:
        lines.append(r"\midrule")
    lines.append(r"\multicolumn{4}{l}{\textit{" + group + r"}}\\")
    for model, label in items:
        r = rows[model]
        lines.append(f"{label} & {f1(r['cloud_ms'])} & {f1(r['balanced_ms'])} & {f1(r['time_ms'])} \\\\")
lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
(ROOT / "paper/tab_boards.tex").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
